const SLIDE_PART = /^ppt\/slides\/slide\d+\.xml$/;

/** Slides are one part each, so a PowerPoint deck can be counted exactly. */
export function countPptxSlides(bytes: Buffer): PageCount {
  const slides = listZip(bytes).filter((entry) => SLIDE_PART.test(entry.name)).length;
  if (slides > 0) return { pages: slides, confidence: 'exact' };

  return { pages: 1, confidence: 'estimated', reason: 'This file has no slide parts. It may not be a .pptx.' };
}

/**
 * A Word document has no page count of its own — pages exist only once
 * something lays the text out. Word records the number it last saw in
 * `docProps/app.xml`, which is right whenever Word saved the file, and stale
 * or missing for a document generated by a script.
 */
export function countDocxPages(bytes: Buffer): PageCount {
  const properties = listZip(bytes).find((entry) => entry.name === 'docProps/app.xml');

  if (properties !== undefined) {
    const app = readZipEntry(bytes, 'docProps/app.xml')?.toString('utf8') ?? '';
    const pages = Number(/<Pages>(\d+)<\/Pages>/.exec(app)?.[1] ?? NaN);

    if (Number.isInteger(pages) && pages >= 1) {
      return pages >= 2
        ? { pages, confidence: 'exact' }
        : {
            pages,
            confidence: 'estimated',
            reason: 'Word reports one page, which is also what it reports for a document it has never laid out.',
          };
    }
  }

  return {
    pages: 1,
    confidence: 'estimated',
    reason: 'This document carries no page count. Open and save it in Word, or convert it, to get a real one.',
  };
}
