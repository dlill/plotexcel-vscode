const MISSING = GLYPHS[' ']!;

/**
 * The seven row patterns for one character.
 *
 * Lower case has its own glyphs rather than borrowing the capitals: a
 * placeholder that reads "File not found" is a message, and one that reads
 * "FILE NOT FOUND" is a shout. Anything with no glyph of its own falls back to
 * its upper-case form, and then to a blank — never to a crash.
 */
export function glyphOf(character: string): readonly string[] {
  const glyph = GLYPHS[character] ?? GLYPHS[character.toUpperCase()] ?? MISSING;
  return glyph.split('/');
}

/** Width in pixels of a string at the given scale, including inter-glyph gaps. */
export function measureText(text: string, scale = 1): number {
  if (text.length === 0) return 0;
  return (text.length * (GLYPH_WIDTH + 1) - 1) * scale;
}

/** Call `plot(x, y)` for every pixel of `text` drawn with its top-left at (0, 0). */
export function drawText(text: string, scale: number, plot: (x: number, y: number) => void): void {
  let cursor = 0;

  for (const character of text) {
    const rows = glyphOf(character);

    rows.forEach((row, y) => {
      for (let x = 0; x < row.length; x += 1) {
        if (row[x] !== '#') continue;
        for (let dy = 0; dy < scale; dy += 1) {
          for (let dx = 0; dx < scale; dx += 1) {
            plot((cursor + x) * scale + dx, y * scale + dy);
          }
        }
      }
    });

    cursor += GLYPH_WIDTH + 1;
  }
}
